/** Fill the `{name}` token with the viewer's first name (fallback: "boss"). */
export const renderWelcome = (msg: string, name?: string | null): string =>
  msg.replaceAll("{name}", (name ?? "").trim().split(/\s+/)[0] || "boss")

/** A random greeting, rendered. Call once per visit (e.g. a useState initializer). */
export const pickWelcome = (name?: string | null): string =>
  renderWelcome(WELCOME_MESSAGES[Math.floor(Math.random() * WELCOME_MESSAGES.length)]!, name)
